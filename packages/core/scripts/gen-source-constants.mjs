// Emit dist/source-constants.cjs from the canonical TypeScript constants in src/source-constants.ts.
//
// The babel plugin is CommonJS tooling that cannot import the ESM build. Before this generator, the
// value was hand-copied and the two sides were kept in sync by comments on each pointing at the
// other — which is how a rename breaks all source mapping silently while every test passes.
//
// Same pattern as gen-desktop-contract.mjs: generate removes the copy rather than policing it.

/** Render the CommonJS module text for a `name → value` record. */
export function renderSourceConstants(constants) {
  const lines = Object.entries(constants).map(
    ([name, value]) => `exports.${name} = ${JSON.stringify(value)};`,
  );
  return [
    '// GENERATED by scripts/gen-source-constants.mjs — do not edit.',
    '//',
    '// The CommonJS view of source-constants, for build tooling (@reticlehq/babel-plugin) that',
    '// cannot import the ESM build. Edit src/source-constants.ts and rebuild @reticlehq/core.',
    "'use strict';",
    ...lines,
    'Object.freeze(exports);',
    '',
  ].join('\n');
}

/** Render the CJS type declaration (.d.cts) for a `name → value` record. */
export function renderSourceConstantsDts(constants) {
  const lines = Object.entries(constants).map(
    ([name, value]) => `export declare const ${name}: ${JSON.stringify(value)};`,
  );
  return ['// GENERATED by scripts/gen-source-constants.mjs — do not edit.', ...lines, ''].join(
    '\n',
  );
}

// ── CLI entry ────────────────────────────────────────────────────────────────────────────────────
const { fileURLToPath } = await import('node:url');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { writeFileSync } = await import('node:fs');
  const { join, dirname } = await import('node:path');
  const { pathToFileURL } = await import('node:url');

  const here = dirname(fileURLToPath(import.meta.url));
  const dist = join(here, '..', 'dist');
  const mod = await import(pathToFileURL(join(dist, 'source-constants.js')).href);
  const constants = {
    DATA_RETICLE_SOURCE_ATTR: mod.DATA_RETICLE_SOURCE_ATTR,
    RETICLE_ROOT_GLOBAL: mod.RETICLE_ROOT_GLOBAL,
    RETICLE_SDK_VERSION_GLOBAL: mod.RETICLE_SDK_VERSION_GLOBAL,
  };
  const outCjs = join(dist, 'source-constants.cjs');
  const outDts = join(dist, 'source-constants.d.cts');
  writeFileSync(outCjs, renderSourceConstants(constants), 'utf8');
  writeFileSync(outDts, renderSourceConstantsDts(constants), 'utf8');
  process.stderr.write(
    `wrote source constants (${String(Object.keys(constants).length)} constants) to dist/source-constants.{cjs,d.cts}\n`,
  );
}
